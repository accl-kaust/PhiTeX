#!/usr/bin/perl
# Generate phitex-biber's Unicode data from the Perl that runs biber:
#   crates/tools/biber/src/unidata.rs   property ranges (Unicode::UCD)
#   crates/tools/biber/data/ducet.bin    Unicode::Collate's DUCET (allkeys.txt)
# Usage: scripts/sandbox perl scripts/biber-tables.pl ISULOWER_RANGES_FILE
# (ISULOWER_RANGES_FILE: btparse's isulower() table, as "(0xA,0xB)," pairs.)
use strict;
use warnings;
use Unicode::UCD qw(prop_invmap prop_invlist);

my $out = 'crates/tools/biber/src/unidata.rs';
open my $o, '>', $out or die "$out: $!";
print $o "//! Unicode property tables, generated by scripts/biber-tables.pl from\n";
print $o "//! Perl's Unicode::UCD (Unicode " . Unicode::UCD::UnicodeVersion() . ") and btparse's isulower().\n";
print $o "//! Do not edit.\n\n";

sub ranges_from_invlist {
  my @l = @_;
  my @r;
  for (my $i = 0; $i < @l; $i += 2) {
    my $s = $l[$i];
    my $e = ($i + 1 < @l) ? $l[$i+1] - 1 : 0x10FFFF;
    push @r, [$s, $e];
  }
  return @r;
}
sub emit_set {
  my ($name, @r) = @_;
  print $o "pub static $name: &[(u32, u32)] = &[\n";
  my $n = 0;
  foreach my $r (@r) {
    printf $o "(0x%X,0x%X),", $r->[0], $r->[1];
    print $o "\n" if ++$n % 8 == 0;
  }
  print $o "\n];\n\n";
}
foreach my $p (['DASH', 'Dash'], ['DIACRITIC', 'Diacritic'], ['WORD', 'Word'],
               ['SPACE', 'XPosixSpace'], ['HSPACE', 'XPosixBlank'],
               ['EXTPICT', 'Extended_Pictographic'], ['ALNUM', 'XPosixAlnum']) {
  emit_set($p->[0], ranges_from_invlist(prop_invlist($p->[1])));
}

# General category: (start, end, index into GC_NAMES)
my @gcnames = qw(Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co Cn);
my %gci; @gci{@gcnames} = (0 .. $#gcnames);
my ($l, $m) = prop_invmap('Gc');
print $o "pub static GC_NAMES: [&str; " . scalar(@gcnames) . "] = [" . join(',', map {"\"$_\""} @gcnames) . "];\n";
print $o "pub static GC: &[(u32, u32, u8)] = &[\n";
my $n = 0;
for (my $i = 0; $i < @$l; $i++) {
  my $s = $l->[$i];
  my $e = ($i + 1 < @$l) ? $l->[$i+1] - 1 : 0x10FFFF;
  my $v = $m->[$i];
  die "gc $v" unless exists $gci{$v};
  printf $o "(0x%X,0x%X,%d),", $s, $e, $gci{$v};
  print $o "\n" if ++$n % 8 == 0;
}
print $o "\n];\n\n";

# Grapheme_Cluster_Break
my @gcb = qw(Other CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark L V T LV LVT E_Base E_Modifier Glue_After_Zwj E_Base_GAZ);
my %gcbi; @gcbi{@gcb} = (0 .. $#gcb);
($l, $m) = prop_invmap('GCB');
print $o "pub static GCB: &[(u32, u32, u8)] = &[\n";
$n = 0;
for (my $i = 0; $i < @$l; $i++) {
  my $v = $m->[$i];
  $v = { ExtPict_XX => "Other", InCB_Consonant_XX => "Other", InCB_Extend_EX => "Extend", InCB_Linker_EX => "Extend" }->{$v} // $v;
  next if $v eq "Other";
  my $s = $l->[$i];
  my $e = ($i + 1 < @$l) ? $l->[$i+1] - 1 : 0x10FFFF;
  die "gcb $v" unless exists $gcbi{$v};
  printf $o "(0x%X,0x%X,%d),", $s, $e, $gcbi{$v};
  print $o "\n" if ++$n % 8 == 0;
}
print $o "\n];\n\n";

# Indic_Conjunct_Break (GB9c)
foreach my $v (['INCB_LINKER', 'Linker'], ['INCB_CONSONANT', 'Consonant'], ['INCB_EXTEND', 'Extend']) {
  my @r;
  my ($il, $im) = prop_invmap('InCB');
  for (my $i = 0; $i < @$il; $i++) {
    next unless $im->[$i] eq $v->[1];
    push @r, [$il->[$i], ($i + 1 < @$il) ? $il->[$i+1] - 1 : 0x10FFFF];
  }
  emit_set($v->[0], @r);
}

# btparse isulower()
open my $isl, '<', $ARGV[0] or die "$ARGV[0]: $!";
my $islt = do { local $/; <$isl> };
my @isl;
while ($islt =~ /\(0x([0-9A-F]+),0x([0-9A-F]+)\)/g) { push @isl, [hex($1), hex($2)] }
emit_set('ISULOWER', @isl);
close $o;

# DUCET, as Unicode::Collate reads allkeys.txt (non-ignorable weights; '*' marks variable).
my $ak;
foreach my $d (@INC) {
  if (-f "$d/Unicode/Collate/allkeys.txt") { $ak = "$d/Unicode/Collate/allkeys.txt"; last }
}
die 'no allkeys.txt' unless $ak;
open my $a, '<', $ak or die "$ak: $!";
my (@entries);
my $version;
while (<$a>) {
  chomp;
  if (/^\@version\s+(\S+)/) { $version = $1; next }
  next if /^\s*(#|\@|$)/;
  my ($cps, $ces) = /^\s*([0-9A-Fa-f ]+?)\s*;\s*((?:\[[^\]]*\])+)/ or next;
  my @cp = map { hex } split ' ', $cps;
  my @ce;
  while ($ces =~ /\[([.*])([0-9A-Fa-f]+)\.([0-9A-Fa-f]+)\.([0-9A-Fa-f]+)(?:\.[0-9A-Fa-f]+)?\]/g) {
    push @ce, [$1 eq '*' ? 1 : 0, hex($2), hex($3), hex($4)];
  }
  push @entries, [\@cp, \@ce];
}
close $a;
# Binary: magic "DUCT", version string (u8 len + bytes), entry count (u32 LE),
# then per entry: n_cp (u8), cps (u32 LE each), n_ce (u8), ces (var u8, p u16, s u16, t u16 LE).
open my $b, '>:raw', 'crates/tools/biber/data/ducet.bin' or die $!;
print $b 'DUCT', pack('C', length $version), $version, pack('V', scalar @entries);
foreach my $e (@entries) {
  print $b pack('C', scalar @{$e->[0]}), pack('V*', @{$e->[0]});
  print $b pack('C', scalar @{$e->[1]});
  print $b pack('Cvvv', @$_) foreach @{$e->[1]};
}
close $b;
print STDERR "unidata.rs + ducet.bin (", scalar(@entries), " DUCET entries, $version)\n";
