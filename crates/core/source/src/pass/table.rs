pub(crate) struct Table {
    pub commands: HashMap<&'static str, Entry>,
    pub envs: HashMap<&'static str, Vec<Arg>>,
}

/// The table, built once.
pub(crate) fn table() -> &'static Table {
    static T: OnceLock<Table> = OnceLock::new();
    T.get_or_init(|| {
        let mut commands = HashMap::new();
        for (list, ty) in [
            (INT_PARAMS, 'i'),
            (DIMEN_PARAMS, 'd'),
            (GLUE_PARAMS, 'g'),
            (TOKS_PARAMS, 't'),
        ] {
            for n in list.split_whitespace() {
                commands.insert(n, Entry::Quantity(ty, None));
            }
        }
        for (n, ty, ix) in [
            ("count", 'i', 'i'),
            ("dimen", 'd', 'i'),
            ("skip", 'g', 'i'),
            ("muskip", 'g', 'i'),
            ("toks", 't', 'i'),
            ("catcode", 'i', 'i'),
            ("lccode", 'i', 'i'),
            ("uccode", 'i', 'i'),
            ("sfcode", 'i', 'i'),
            ("mathcode", 'i', 'i'),
            ("delcode", 'i', 'i'),
            ("wd", 'd', 'i'),
            ("ht", 'd', 'i'),
            ("dp", 'd', 'i'),
            ("fontdimen", 'd', 'F'),
            ("lpcode", 'i', 'F'),
            ("rpcode", 'i', 'F'),
            ("efcode", 'i', 'F'),
        ] {
            commands.insert(n, Entry::Quantity(ty, Some(ix)));
        }
        for &(n, spec) in COMMANDS {
            if !commands.contains_key(n) {
                commands.insert(n, Entry::Command(compile(spec)));
            }
        }
        let envs = ENVIRONMENTS.iter().map(|&(n, s)| (n, compile(s))).collect();
        Table { commands, envs }
    })
}

/// A spec's arguments.
pub(crate) fn compile(spec: &str) -> Vec<Arg> {
    let mut out = Vec::new();
    for (k, c) in spec.char_indices() {
        out.push(match c {
            's' => Arg::Star,
            'o' => Arg::Opt,
            'm' => Arg::M,
            'N' => Arg::Tok,
            'c' => Arg::Relation,
            'P' => Arg::ParamText,
            'B' => Arg::Group,
            'b' => Arg::BoxSpec,
            'e' => Arg::Eq,
            'i' => Arg::Int,
            'd' => Arg::Dimen,
            'g' => Arg::Glue,
            'v' => Arg::Value,
            'R' => Arg::Reg,
            'C' => Arg::CsName,
            'X' => Arg::Expr,
            'f' => Arg::File,
            'T' => Arg::Toks,
            'r' => Arg::Rule,
            'k' => Arg::By,
            't' => Arg::To,
            'l' => Arg::LetTarget,
            'F' => Arg::FontSize,
            'K' => Arg::Keywords,
            'Y' => Arg::Tikz,
            ';' => Arg::Semicolon,
            'V' => Arg::Verb,
            'E' => Arg::Env,
            '*' => Arg::StarSkip,
            'U' => {
                out.push(Arg::UntilCs(spec[k + 1..].to_owned()));
                return out;
            }
            '!' => {
                out.push(Arg::Pending(spec[k + 1..].to_owned()));
                return out;
            }
            _ => unreachable!("spec letter {c}"),
        });
    }
    out
}
